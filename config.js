/* ---------- Validation ---------- */

// Project ids are UUIDs generated by the server. A value taken from a URL ends up in a file path, so it is
// validated strictly (otherwise "../" could escape data/).
export const isValidId = (id) => typeof id === 'string' && /^[A-Za-z0-9-]{8,64}$/.test(id);
