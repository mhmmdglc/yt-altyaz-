// Shared configuration: paths, external tools, model locations. Everything can be overridden with environment variables (docs/CONFIGURATION.md).
import { existsSync, accessSync, constants, statSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.dirname(fileURLToPath(import.meta.url));
export const IS_WINDOWS = process.platform === 'win32';

// Launchers such as Finder or the Start menu give the app a minimal PATH: add the usual install folders
if (!IS_WINDOWS) {
  const extra = ['/opt/homebrew/bin', '/usr/local/bin', '/home/linuxbrew/.linuxbrew/bin', path.join(os.homedir(), '.local', 'bin')];
  const have = new Set((process.env.PATH || '').split(path.delimiter));
  process.env.PATH = [...(process.env.PATH || '').split(path.delimiter), ...extra.filter((d) => !have.has(d))].join(path.delimiter);
}

export const HOST = process.env.HOST || '127.0.0.1'; // default: this computer only
export const PORT = Number(process.env.PORT) || 3000;
export const DATA_DIR = path.resolve(process.env.DATA_DIR || path.join(ROOT, 'data'));
export const WORK_DIR = path.resolve(process.env.WORK_DIR || path.join(ROOT, 'work'));
export const MODELS_DIR = path.resolve(process.env.MODELS_DIR || path.join(ROOT, 'models'));

/* ---------- External tools ---------- */

// Looks for an executable on PATH (with .exe/.cmd extensions on Windows)
export function which(name) {
  if (path.isAbsolute(name)) return existsSync(name) ? name : null;
  const exts = IS_WINDOWS ? ['.exe', '.cmd', '.bat', ''] : [''];
  for (const dir of (process.env.PATH || '').split(path.delimiter)) {
    for (const ext of exts) {
      const file = path.join(dir, name + ext);
      try {
        if (statSync(file).isFile()) { accessSync(file, constants.X_OK); return file; }
      } catch { /* sonraki */ }
    }
  }
  return null;
}

const firstFound = (envName, candidates) => {
  const forced = process.env[envName];
  if (forced) return forced;
  return candidates.find((c) => which(c)) || candidates[0];
};

export const bin = {
  get ytdlp() { return firstFound('YTDLP_BIN', ['yt-dlp']); },
  get ffmpeg() { return firstFound('FFMPEG_BIN', ['ffmpeg']); },
  get whisper() { return firstFound('WHISPER_BIN', ['whisper-cli', 'whisper-cpp']); },
  get llamaServer() { return firstFound('LLAMA_SERVER_BIN', ['llama-server']); }
};

/* ---------- Whisper model ---------- */

// English-only models (word-level output is needed for sentence timing). Sizes are approximate.
export const WHISPER_MODELS = {
  'medium.en': { file: 'ggml-medium.en.bin', size: '1.5 GB', note: 'best accuracy (recommended)' },
  'small.en': { file: 'ggml-small.en.bin', size: '466 MB', note: 'faster, a bit less accurate' },
  'base.en': { file: 'ggml-base.en.bin', size: '142 MB', note: 'fastest, lowest accuracy' }
};
export const whisperModelUrl = (name) => `https://huggingface.co/ggerganov/whisper.cpp/resolve/main/${WHISPER_MODELS[name].file}`;

// Path of the Whisper model to use: WHISPER_MODEL (name or path), otherwise the best installed model
export function findWhisperModel() {
  const forced = process.env.WHISPER_MODEL;
  if (forced) {
    if (WHISPER_MODELS[forced]) return existsSync(path.join(MODELS_DIR, WHISPER_MODELS[forced].file)) ? path.join(MODELS_DIR, WHISPER_MODELS[forced].file) : null;
    return existsSync(forced) ? forced : null;
  }
  for (const m of Object.values(WHISPER_MODELS)) {
    const file = path.join(MODELS_DIR, m.file);
    if (existsSync(file)) return file;
  }
  return null;
}

